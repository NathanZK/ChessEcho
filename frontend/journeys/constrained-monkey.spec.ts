import fs from 'node:fs';
import { test, expect } from '@playwright/test';
import {
  setupJourneyApiMocks,
  DEFAULT_MOCK_ACCOUNT,
  DEFAULT_MOCK_PUZZLE,
} from './fixtures/mockApi';
import { runConstrainedMonkey } from './model/monkeyRunner';

test.describe('Phase 4: Constrained Monkey Testing with Playwright', () => {
  test('Bounded monkey run executes valid state-constrained sequence within action budget', async ({ page }) => {
    // 1. Setup mocked API boundaries
    await setupJourneyApiMocks(page, {
      authenticated: true,
      accounts: [DEFAULT_MOCK_ACCOUNT],
      puzzles: [DEFAULT_MOCK_PUZZLE],
    });

    // 2. Navigate to practice tab
    await page.goto('/#puzzles');

    // 3. Execute 10-step bounded monkey run starting from discovery
    const seed = 20261108;
    const result = await runConstrainedMonkey({
      page,
      seed,
      actionBudget: 10,
      initialState: 'DISCOVERY',
    });

    if (!result.success) {
      console.error(result.error?.message);
    }
    expect(result.success).toBe(true);
    expect(result.executedSteps).toBeGreaterThanOrEqual(1);
    expect(result.actionLog.length).toBe(result.executedSteps);

    // Verify all logged steps have valid state transitions
    for (const entry of result.actionLog) {
      expect(entry.fromState).toBeDefined();
      expect(entry.action).toBeDefined();
      expect(entry.toState).toBeDefined();
    }
  });

  test('Deterministic seed replay generates identical action sequences across independent runs', async ({ page }) => {
    await setupJourneyApiMocks(page, {
      authenticated: true,
      accounts: [DEFAULT_MOCK_ACCOUNT],
      puzzles: [DEFAULT_MOCK_PUZZLE],
    });

    await page.goto('/#puzzles');

    const seed = 777;
    const run1 = await runConstrainedMonkey({
      page,
      seed,
      actionBudget: 6,
      initialState: 'DISCOVERY',
    });

    expect(run1.success).toBe(true);

    // Reload and replay under identical seed
    await page.reload();
    const run2 = await runConstrainedMonkey({
      page,
      seed,
      actionBudget: 6,
      initialState: 'DISCOVERY',
    });

    expect(run2.success).toBe(true);
    expect(run1.actionLog.map((e) => e.action)).toEqual(run2.actionLog.map((e) => e.action));
    expect(run1.actionLog.map((e) => e.fromState)).toEqual(run2.actionLog.map((e) => e.fromState));
    expect(run1.actionLog.map((e) => e.toState)).toEqual(run2.actionLog.map((e) => e.toState));
  });

  test('Deliberately induced failure captures deterministic seed, action log, screenshot, and trace archive', async ({ page }) => {
    await setupJourneyApiMocks(page, {
      authenticated: true,
      accounts: [DEFAULT_MOCK_ACCOUNT],
      puzzles: [DEFAULT_MOCK_PUZZLE],
    });

    await page.goto('/#puzzles');

    const failureSeed = 999001;
    const result = await runConstrainedMonkey({
      page,
      seed: failureSeed,
      actionBudget: 5,
      initialState: 'DISCOVERY',
      screenshotOnFailure: true,
      stepHook: async (step) => {
        if (step === 1) {
          await page.evaluate(() => {
            console.error('Deliberately induced runtime error for monkey failure testing');
          });
        }
      },
    });

    // Must report failure with rich diagnostic context
    expect(result.success).toBe(false);
    expect(result.error).toBeDefined();
    expect(result.error?.message).toContain(`Seed: ${failureSeed}`);
    expect(result.error?.message).toContain('Oracle 1 Failure');
    expect(result.error?.message).toContain('Deliberately induced runtime error');

    // Must produce on-disk screenshot and Playwright trace archive
    expect(result.screenshotPath).toBeDefined();
    expect(result.tracePath).toBeDefined();
    expect(fs.existsSync(result.screenshotPath!)).toBe(true);
    expect(fs.existsSync(result.tracePath!)).toBe(true);

    // Clean up temporary failure artifacts generated by this test
    if (result.screenshotPath && fs.existsSync(result.screenshotPath)) {
      fs.unlinkSync(result.screenshotPath);
    }
    if (result.tracePath && fs.existsSync(result.tracePath)) {
      fs.unlinkSync(result.tracePath);
    }
  });
});
